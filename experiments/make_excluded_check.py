"""Real-model check of the task x fault pairs that the mock dependence filter
EXCLUDED (no candidate patch changed the mock outcome). The filter says these
faults cannot matter to an agent that plans optimally on the facts it is
given; this checks whether they matter to the real model.

Writes data/tasks_excluded_check.json (one task per excluded candidate patch;
extra candidates for the same task get suffixes b, c, ...) and
configs/excluded_check[_mock].yaml (results -> results/excluded_check, so the
main results and analyze.py are untouched). Then run:

    python experiments/make_excluded_check.py
    python experiments/run_faults.py --config configs/excluded_check.yaml --workers 6
"""
from __future__ import annotations

import copy
import json
import string
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from src.environment import CourseEnrollmentEnv  # noqa: E402
from src.fault_injection import candidate_patches, load_fault_specs  # noqa: E402


def main():
    cfg = yaml.safe_load(open(ROOT / "configs" / "experiment.yaml"))
    specs = {s.id: s for s in load_fault_specs(cfg["faults"]) if s.kind != "none"}
    tasks = json.load(open(ROOT / "data" / "tasks.json"))["tasks"]
    out = []
    for t in tasks:
        for fid, spec in specs.items():
            if fid in t["valid_faults"]:
                continue
            facts = CourseEnrollmentEnv(t["inputs"]["scenario"]).true_facts()
            for k, (patch, desc) in enumerate(candidate_patches(spec.type, t, facts)):
                c = copy.deepcopy(t)
                c["task_id"] = t["task_id"] + ("" if k == 0 else string.ascii_lowercase[k])
                c["base_task_id"] = t["task_id"]
                c["faults"] = {fid: {"patch": patch, "description": desc, "harmful": False,
                                     "excluded_by_filter": True}}
                c["valid_faults"] = [fid]
                out.append(c)
                print(f"{c['task_id']:6s} {fid:26s} {desc}")
    (ROOT / "data" / "tasks_excluded_check.json").write_text(
        json.dumps({"note": "pairs excluded by the mock dependence filter", "tasks": out}, indent=1))
    for name, base in [("excluded_check", "experiment"), ("excluded_check_mock", "mock")]:
        c = yaml.safe_load(open(ROOT / "configs" / f"{base}.yaml"))
        c["workflow"]["tasks_file"] = "data/tasks_excluded_check.json"
        sub = "excluded_check" + ("/mock" if base == "mock" else "")
        c["output"] = {**c["output"], "results_dir": f"results/{sub}", "traces_dir": f"results/{sub}/traces"}
        (ROOT / "configs" / f"{name}.yaml").write_text(
            f"# generated by experiments/make_excluded_check.py from {base}.yaml\n" + yaml.safe_dump(c, sort_keys=False))
    print(f"{len(out)} check tasks -> data/tasks_excluded_check.json")


if __name__ == "__main__":
    main()
